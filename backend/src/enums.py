"""
enums.py — ПЕРЕЧИСЛЕНИЯ (фиксированный набор значений).

Enum (перечисление) — это тип, у которого может быть только несколько
заранее известных значений. Мы используем его для роли пользователя:
человек может быть либо обычным пользователем, либо администратором —
третьего не дано.

Зачем так, а не просто строка «user» / «admin» в коде?
- Нельзя случайно написать «admn» с опечаткой — Python не примет неизвестное значение.
- В одном месте видно все возможные роли.
- И модель, и схемы, и зависимости берут значения из ОДНОГО источника.
"""

from enum import Enum


class UserRole(str, Enum):
    """Роль пользователя в системе.

    Наследуемся сразу от str и Enum:
    - Enum даёт список допустимых значений;
    - str позволяет класть роль в базу и в JSON как обычную строку
      («user», «admin»), а не как сложный объект.
    """

    USER = "user"      # обычный пользователь: свои данные, список людей
    ADMIN = "admin"    # администратор: всё то же + смена ролей других людей
