"""
exceptions.py — ОШИБКИ ПРЕДМЕТНОЙ ОБЛАСТИ.

Зачем это нужно, если есть `HTTPException` из FastAPI?

`HTTPException` — это понятие веба. Если сервисный слой будет его бросать,
он окажется привязан к HTTP: тот же код нельзя будет вызвать ни из фоновой
задачи, ни из консольной команды, ни из теста без поднятия приложения.

Поэтому сервисы бросают ошибки из этого файла — на языке предметной области
(«не найдено», «уже занято», «нет прав»). А превращением их в HTTP-ответы
занимается один обработчик в `src/main.py`. Правило простое:

    сервис знает, ЧТО не так;
    слой api знает, какой у этого КОД ОТВЕТА.
"""


class AppError(Exception):
    """Базовая ошибка приложения. От неё наследуются все остальные."""

    status_code: int = 500
    detail: str = "Внутренняя ошибка сервера"
    headers: dict[str, str] | None = None

    def __init__(self, detail: str | None = None) -> None:
        # Если текст не передали — берём тот, что указан в классе.
        if detail is not None:
            self.detail = detail
        super().__init__(self.detail)


class NotFoundError(AppError):
    """Объекта нет — или он есть, но этому человеку его видеть нельзя.

    Второй случай тоже 404, а не 403: иначе по коду ответа можно было бы
    узнать, что чужая запись существует.
    """

    status_code = 404
    detail = "Объект не найден"


class ConflictError(AppError):
    """Данные противоречат уже существующим: логин занят, почта занята."""

    status_code = 400
    detail = "Конфликт данных"


class ValidationError(AppError):
    """Запрос синтаксически верный, но по смыслу недопустим.

    Например, неверный текущий пароль при смене или попытка заблокировать
    себя. Это 400: человек уже вошёл, ошибка в содержании запроса.
    """

    status_code = 400
    detail = "Недопустимые данные"


class AuthenticationError(AppError):
    """Непонятно, кто это: нет токена, он испорчен или просрочен."""

    status_code = 401
    detail = "Неверный или просроченный токен"
    headers = {"WWW-Authenticate": "Bearer"}


class PermissionDeniedError(AppError):
    """Кто это — понятно, но прав на действие не хватает."""

    status_code = 403
    detail = "Недостаточно прав"
